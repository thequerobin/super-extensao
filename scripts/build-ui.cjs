const fs = require('node:fs');
const path = require('node:path');
const { renderUi } = require('../ui/render.cjs');
const { catalog } = require('../ui/render.cjs');
const { createUi } = require('../ui/dom.cjs');
const root = path.resolve(__dirname, '..');
const templates = path.join(root, 'ui/templates');
const entries = { 'popup.html': 'popup.html', 'spare-tab.html': 'spare-tab.html', 'newtab/index.html': 'newtab.html' };

function readTemplate(file, parents = []) {
  const absolute = path.resolve(templates, file);
  if (!absolute.startsWith(templates + path.sep) || parents.includes(absolute)) throw new Error(`Invalid template include: ${file}`);
  return fs.readFileSync(absolute, 'utf8').replace(/<!-- include:([\w/.-]+) -->/g,
    (_, include) => readTemplate(include, [...parents, absolute]));
}

function buildUi(check = false) {
  const runtime = `/* Generated by npm run build:ui. Edit ui/dom.cjs and ui/catalog.json. */\n(() => {\nconst catalog = ${JSON.stringify(catalog)};\nconst createUi = ${createUi.toString()};\nglobalThis.SuperUi = Object.freeze({create: (name, options, children) => createUi(document, catalog, name, options, children)});\n})();\n`;
  if (check) {
    if (fs.readFileSync(path.join(root, 'ui.js'), 'utf8').replace(/\r\n/g, '\n') !== runtime.replace(/\r\n/g, '\n')) throw new Error('Outdated UI artifact: ui.js');
  } else fs.writeFileSync(path.join(root, 'ui.js'), runtime);
  for (const [file, template] of Object.entries(entries)) {
    const html = '<!-- Generated by npm run build:ui. Edit ui/templates/ instead. -->\n' + renderUi(readTemplate(template));
    const output = path.join(root, file);
    if (check) {
      if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== html.replace(/\r\n/g, '\n')) throw new Error(`Outdated UI artifact: ${file}`);
    } else fs.writeFileSync(output, html);
  }
}

if (require.main === module) buildUi(process.argv.includes('--check'));
module.exports = { buildUi };
